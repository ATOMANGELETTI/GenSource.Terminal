export function resolveVscodeFileIcon(
  fileName: string,
  extension: string,
): IconifyIcon {
  const base = fileName.toLowerCase();
  const byName = BASENAME_ICONS[base];
  const iconName =
    byName ??
    EXTENSION_ICONS[extension] ??
    ('default-file' satisfies VscodeFileIconName);

  const data = VSCODE_FILE_ICONS[iconName] ?? VSCODE_FILE_ICONS['default-file'];
  return {
    body: data.body,
    width: VSCODE_ICON_WIDTH,
    height: VSCODE_ICON_HEIGHT,
  };
}
